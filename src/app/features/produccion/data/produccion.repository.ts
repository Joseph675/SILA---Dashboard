import type { Observable } from 'rxjs';
import type { Page, PageQuery } from '../../../core/api/page.models';
import type { Ajuste, AjustesQuery, Lote, LotesQuery, NuevoAjuste, NuevoLote } from '../models/produccion.models';

/**
 * Data contract of the Producción screen (through PRODUCCION_REPOSITORY).
 *
 * Errors arrive as `ApiError`: 20001 invalid data (`fields`), 20002 the adjustment would leave
 * negative stock, 20004 closed quincena, 20006, 20008 role (ADMIN-only adjustment types),
 * 20016 / 20017 idempotency.
 */
export abstract class ProduccionRepository {
  abstract listarLotes(query: PageQuery & LotesQuery): Observable<Page<Lote>>;
  /** Requires `Idempotency-Key`. The lote code is generated by the database. */
  abstract crearLote(datos: NuevoLote, claveIdempotencia: string): Observable<Lote>;
  abstract listarAjustes(query: PageQuery & AjustesQuery): Observable<Page<Ajuste>>;
  /** Requires `Idempotency-Key`. */
  abstract crearAjuste(datos: NuevoAjuste, claveIdempotencia: string): Observable<Ajuste>;
}
